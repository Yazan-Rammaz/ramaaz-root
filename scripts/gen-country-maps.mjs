#!/usr/bin/env node
/**
 * Generates the country map thumbnails in public/icons/maps (one SVG per ISO
 * 3166-1 alpha-2 code) and src/features/region/map-sizes.ts (their XD sizes).
 *
 * Source: Natural Earth 1:50m via world-atlas (public domain). Style follows
 * the XD Turkiye thumbnail (regions/geo/map-turkiye.png): a flat #6F9C76 fill,
 * 62 x 26 XD px for a wide country.
 *
 * Drawing (projection, distant territories dropped, specks removed) is shared
 * with the region maps: scripts/geo-svg.mjs.
 *
 * Run once; the output is committed. Re-run only if the style or data changes:
 *   node scripts/gen-country-maps.mjs
 */
import {
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { createRequire } from "node:module";
import { feature } from "topojson-client";
import countries from "i18n-iso-countries";
import { renderThumb } from "./geo-svg.mjs";

const require = createRequire(import.meta.url);
const topo = JSON.parse(
  readFileSync(require.resolve("world-atlas/countries-50m.json"), "utf8"),
);

const FILL = "#6F9C76";
/** The XD Turkiye thumbnail's box: wide shapes fit 62 x 26. */
const WIDE = { w: 62, h: 26 };
/** Tall shapes (Chile, Norway) may grow to this height so they stay visible. */
const TALL_H = 36;

/** world-atlas features without a numeric ISO id, by name. */
const BY_NAME = { Kosovo: "xk" };

const outDir = new URL("../public/icons/maps/", import.meta.url);
mkdirSync(outDir, { recursive: true });
// Only this script's own files: the region maps live in a folder beside them.
for (const file of readdirSync(outDir)) {
  if (file.endsWith(".svg")) rmSync(new URL(file, outDir));
}

function boxFor(aspect) {
  if (aspect >= WIDE.w / WIDE.h) return { w: WIDE.w, h: WIDE.w / aspect };
  if (aspect >= 1) return { w: WIDE.h * aspect, h: WIDE.h };
  return { w: TALL_H * aspect, h: TALL_H };
}

const sizes = {};
for (const raw of feature(topo, topo.objects.countries).features) {
  const code = (
    countries.numericToAlpha2(raw.id ?? "") ??
    BY_NAME[raw.properties?.name] ??
    ""
  ).toLowerCase();
  if (!code || sizes[code]) continue;

  const thumb = renderThumb(raw, { fill: FILL, boxFor });
  if (!thumb) continue;
  writeFileSync(new URL(`${code}.svg`, outDir), thumb.svg);
  sizes[code] = [thumb.w, thumb.h];
}

const entries = Object.keys(sizes)
  .sort()
  .map((c) => `  ${c}: [${sizes[c][0]}, ${sizes[c][1]}],`)
  .join("\n");
writeFileSync(
  new URL("../src/features/region/map-sizes.ts", import.meta.url),
  `/**
 * The ISO 3166-1 alpha-2 codes with a map thumbnail in \`/public/icons/maps\`,
 * and its [width, height] in XD px. Generated by scripts/gen-country-maps.mjs
 * (Natural Earth 1:50m) — do not edit by hand; re-run the script.
 */
export const MAP_SIZES: Readonly<Record<string, readonly [number, number]>> = {
${entries}
};
`,
);
console.log(`${Object.keys(sizes).length} country maps written`);

// Alpha-3 → alpha-2, so a country saved as JOR finds the same flag and map as JO.
const alpha3 = Object.entries(countries.getAlpha3Codes())
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([a3, a2]) => `${a3}:${a2}`)
  .join(" ");
writeFileSync(
  new URL("../src/features/region/iso-alpha3.ts", import.meta.url),
  `/**
 * ISO 3166-1 alpha-3 → alpha-2 (JOR → JO). Generated by
 * scripts/gen-country-maps.mjs from i18n-iso-countries — do not edit by hand.
 */
export const ALPHA3_TO_ALPHA2: ReadonlyMap<string, string> = new Map(
  "${alpha3}"
    .split(" ")
    .map((pair) => pair.split(":") as [string, string]),
);
`,
);
